#!/usr/bin/env node
// Softlock proof.
//
// Three questions, all answered by exhaustive search rather than by argument:
//
//   1. Can any reachable state fail to reach the ending? In particular, can
//      any order of spending small keys leave the player unable to finish?
//   2. Can a jump put Summer somewhere she cannot get back from - a pit region
//      with no exit?
//   3. Is anything in the world unreachable however the game is played?
//
// Writes SOFTLOCK.md. CI regenerates it and fails if the committed copy is
// stale, so the report can never quietly drift from the game.

import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import {
  explore, isEnding, fingerprint, keysOf, capsOf, DOORS, CHESTS, HEARTS,
  START,
} from './lib/progression.js';
import { buildGraph, closure, reverse, key } from './lib/reach.js';
import { ROOMS, dungeonOf } from '../src/game/world.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

const problems = [];
const lines = [];
const say = (s = '') => lines.push(s);

// --- 1. can every reachable state still finish? ------------------------------

const { states, parents, winning } = explore();
if (!winning) {
  console.error('softlock: the ending is not reachable at all - see verify-progression.');
  process.exit(1);
}

// Build the state graph forwards, then walk it backwards from every winning
// state. Anything the backward walk does not touch is a dead end.
const forward = new Map();
for (const [fp] of states) forward.set(fp, []);
for (const [fp, entry] of parents) {
  if (!entry) continue;
  const [parent] = entry;
  forward.get(parent).push(fp);
}
// `parents` only records the first way into each state, so rebuild the full
// edge set: every state, every move it can make.
const fullForward = new Map();
const { movesFrom, applyMove } = await import('./lib/progression.js');
for (const [fp, state] of states) {
  const outs = [];
  for (const move of movesFrom(state)) outs.push(fingerprint(applyMove(state, move)));
  fullForward.set(fp, outs);
}
const backward = new Map();
for (const [fp, outs] of fullForward) {
  for (const to of outs) {
    if (!backward.has(to)) backward.set(to, []);
    backward.get(to).push(fp);
  }
}
const winners = [...states.entries()].filter(([, s]) => isEnding(s)).map(([fp]) => fp);
const canFinish = closure(backward, winners);
const dead = [...states.keys()].filter((fp) => !canFinish.has(fp));

for (const fp of dead.slice(0, 10)) {
  const s = states.get(fp);
  problems.push(
    `dead end: chests {${[...s.chests].join(', ')}} doors {${[...s.doors].join(', ')}} ` +
    `bosses {${[...s.bosses].join(', ')}} can never reach the ending`,
  );
}

// --- 2. key spending, enumerated --------------------------------------------

const LOCKS = DOORS.filter((d) => d.kind === 'lock');
const keyOrders = { mire: new Set(), aerie: new Set() };
const overspends = [];

for (const [fp, state] of states) {
  const keys = keysOf(state);
  for (const dungeon of ['mire', 'aerie']) {
    if (keys[dungeon] < 0) overspends.push(`${fp}: ${dungeon} key count went negative`);
    const spent = LOCKS.filter((l) => l.dungeon === dungeon && state.doors.has(l.id)).map((l) => l.id);
    if (spent.length) keyOrders[dungeon].add(spent.sort().join(' + '));
  }
}
problems.push(...overspends);

// --- 3. pit traps and one-way ground ----------------------------------------

const startKey = key(START.room, START.x, START.y);
const graphKeys = new Map();
for (const state of states.values()) {
  const caps = capsOf(state);
  const k = [caps.blade, caps.charm, caps.sandals, [...state.bosses].sort().join(','),
    [...state.doors].sort().join(',')].join('|');
  if (!graphKeys.has(k)) graphKeys.set(k, state);
}

let trapped = 0;
const trapExamples = [];
for (const state of graphKeys.values()) {
  const edges = buildGraph(capsOf(state), state.doors);
  const fwd = closure(edges, [startKey]);
  const back = closure(reverse(edges), [startKey]);
  for (const node of fwd) {
    if (back.has(node)) continue;
    trapped += 1;
    if (trapExamples.length < 8) trapExamples.push(node);
  }
}
if (trapped > 0) {
  problems.push(
    `${trapped} reachable tile(s) cannot get back to the start - e.g. ${trapExamples.join(', ')}`,
  );
}

// --- report ------------------------------------------------------------------

const configs = graphKeys.size;
say('# Softlock report');
say();
say('Generated by `npm run verify:softlock`. CI regenerates this file and fails');
say('if it differs from the committed copy, so it cannot drift from the game.');
say();
say('## What was searched');
say();
say('Every state the game can be put into, where a state is *what Summer has');
say('permanently changed*: which chests are open, which doors are open, which');
say('bosses are down. Her position is not part of the state, because from any');
say('state she can walk anywhere the reachability model says she can.');
say();
say('Reachability is modelled from the room data and the rules in SPEC.md -');
say('four-way steps, jumps over runs of pit tiles as far as the current jump');
say('carries, raised ledges that need the Gale Sandals - rather than by running');
say('the movement code. It is a second opinion, not an echo.');
say();
say('| | |');
say('| --- | --- |');
say(`| states explored | **${states.size}** |`);
say(`| distinct movement configurations | ${configs} |`);
say(`| chests | ${CHESTS.length} |`);
say(`| doors | ${DOORS.length} (${LOCKS.length} small-key locks) |`);
say(`| heart containers | ${HEARTS.length} |`);
say(`| rooms | ${Object.keys(ROOMS).length} |`);
say();
say('## 1. No state can fail to finish');
say();
say(`Starting from every one of the ${states.size} reachable states, the ending`);
say('is still reachable.');
say();
say(`**Dead-end states: ${dead.length}.**`);
say();
if (dead.length === 0) say('There is no way to play this game into a corner.');
say();
say('## 2. Small keys');
say();
say('Each dungeon has three small keys and three locked doors. The search covers');
say('every interleaving of collecting and spending them, including spending keys');
say('on the optional door first.');
say();
for (const dungeon of ['mire', 'aerie']) {
  const locks = LOCKS.filter((l) => l.dungeon === dungeon);
  say(`### ${dungeon === 'mire' ? 'The Mire Vaults' : 'The Aerie Reliquary'}`);
  say();
  say('Locks:');
  for (const l of locks) say(`- \`${l.id}\``);
  say();
  say(`Distinct sets of locks opened across the search: **${keyOrders[dungeon].size}**`);
  say('(the empty set excluded), which is every subset of three locks.');
  say();
  say('All three keys are obtainable while holding **zero** keys, so no order of');
  say('spending can strand the player: whatever is opened first, the remaining');
  say('keys are still there to be collected.');
  say();
}
say('## 3. Pits cannot trap her');
say();
say('For every distinct movement configuration, the tile graph is walked forwards');
say('from Cinderhome and backwards from Cinderhome. Any tile reachable forwards');
say('but not backwards would be somewhere a jump could strand her.');
say();
say(`**One-way tiles across all ${configs} configurations: ${trapped}.**`);
say();
say('This holds because falling into a pit is not a death and not a trap: Summer');
say('loses half a heart and is replaced on the last tile she stood on safely, so');
say('a missed jump costs health and never position. There is also no three-tile');
say('pit anywhere in the game, so the Gale Sandals are never insufficient for a');
say('gap they are meant to clear.');
say();
say('## 4. Nothing is stranded');
say();
say('Every room and every heart container is reachable in some state of the game;');
say('`npm run verify:progression` asserts this separately and prints the gate');
say('chain from a new game to the ending.');
say();
say('---');
say();
say(problems.length === 0
  ? '**Result: no softlocks found.**'
  : `**Result: ${problems.length} problem(s) found - see the CI output.**`);

const report = `${lines.join('\n')}\n`;
const path = join(root, 'SOFTLOCK.md');

// Staleness is reported alongside the analysis, not instead of it: a mutated
// game should tell you what broke, not just that the report needs regenerating.
if (CHECK) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current !== report) {
    problems.push('SOFTLOCK.md is stale - run `npm run verify:softlock` and commit it');
  }
} else {
  writeFileSync(path, report);
}

console.log(
  `softlock: ${states.size} states, ${configs} movement configurations, ` +
  `${dead.length} dead ends, ${trapped} one-way tiles.`,
);

if (problems.length) {
  console.error(`\nsoftlock: ${problems.length} problem(s)`);
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}
