// --- slice the 16x16 art into a deduplicated 8x8 tile table -----------------

/** @type {string[][]} every distinct 8x8 tile, as 8 rows of 8 palette digits */
export const TILES = [];
const tileIndex = new Map();

function internTile(rows) {
  const key = rows.join('');
  if (tileIndex.has(key)) return tileIndex.get(key);
  const id = TILES.length;
  TILES.push(rows);
  tileIndex.set(key, id);
  return id;
}

function sliceMetatile(art) {
  const quadrant = (ox, oy) =>
    art.slice(oy, oy + 8).map((row) => row.slice(ox, ox + 8));
  return [
    internTile(quadrant(0, 0)),
    internTile(quadrant(8, 0)),
    internTile(quadrant(0, 8)),
    internTile(quadrant(8, 8)),
  ];
}

/**
 * Metatile name -> [topLeft, topRight, bottomLeft, bottomRight] tile ids.
 * @type {Record<string, number[]>}
 */
export const METATILES = {};
for (const [name, art] of Object.entries(ART)) {
  if (art.length !== 16 || art.some((row) => row.length !== 16)) {
    throw new Error(`metatile "${name}" must be 16 rows of 16 characters`);
  }
  METATILES[name] = sliceMetatile(art);
}

