/** Glyph name -> 7 rows of 5 characters ('#' ink, '.' clear). */
export const FONT = Object.fromEntries(
  Object.entries(G).map(([ch, spec]) => [ch, spec.split('/')]),
);

export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const CELL_W = 6;
export const CELL_H = 8;

/** Characters the font cannot draw are rendered as a space. */
export function glyph(ch) {
  return FONT[ch] ?? FONT[ch.toUpperCase()] ?? FONT[' '];
}
